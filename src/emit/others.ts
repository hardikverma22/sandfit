import { stringify as tomlStringify } from "smol-toml";
import { stringify as yamlStringify } from "yaml";
import { tempRoots } from "../policy/paths.js";
import type { Policy } from "../types.js";

const HARNESS_DIRS = ["~/.claude", "~/.claude.json", "~/.codex"];

/**
 * Anthropic sandbox-runtime (`srt`) settings, usually ~/.srt-settings.json.
 * srt typically wraps the whole agent process, so harness-tool needs are included.
 * Docs: https://github.com/anthropics/sandbox-runtime
 */
export function toSrtSettings(policy: Policy): Record<string, unknown> {
  const projectSecrets = policy.filesystem.denyRead.filter((p) => p.startsWith("./") && !p.includes("*"));
  return {
    network: {
      allowedDomains: uniq([...policy.network.allowDomains, ...policy.harnessTools.allowFetch]),
      deniedDomains: policy.network.denyDomains,
      ...(policy.network.allowLocalBinding ? { allowLocalBinding: true } : {}),
      ...(policy.network.allowUnixSockets.length ? { allowUnixSockets: policy.network.allowUnixSockets } : {}),
    },
    filesystem: {
      denyRead: [...policy.filesystem.denyRead.filter((p) => !p.startsWith("./")), ...projectSecrets.map((p) => p.slice(2))],
      allowWrite: uniq([".", ...tempRoots(), ...policy.filesystem.allowWrite, ...policy.harnessTools.allowWrite, ...HARNESS_DIRS]),
      denyWrite: policy.filesystem.denyWrite.map((p) => (p.startsWith("./") ? p.slice(2) : p)),
    },
  };
}

/**
 * Codex CLI config.toml. The classic form (sandbox_mode + [sandbox_workspace_write]) is
 * stable; it only has an on/off network switch, so the per-domain list is also available as a
 * permission profile (beta) when `profile` is requested. The two forms are mutually exclusive:
 * if sandbox_mode is set in any config layer, Codex uses it and ignores default_permissions.
 * Docs: https://developers.openai.com/codex/permissions
 */
export function toCodexToml(policy: Policy, opts: { profile?: boolean } = {}): string {
  const header = [
    `# Generated by ${policy.generatedBy} from ${policy.source.events} tool calls across ${policy.source.sessions} session${policy.source.sessions === 1 ? "" : "s"}.`,
    `# Review before use. Every grant is explained in the policy file (sandfit emit --target policy).`,
  ].join("\n");
  const writable = uniq([...policy.filesystem.allowWrite, ...policy.harnessTools.allowWrite]);
  const needsNet = policy.network.allowDomains.length > 0;

  if (!opts.profile) {
    const doc = {
      sandbox_mode: "workspace-write",
      approval_policy: "on-request",
      sandbox_workspace_write: { network_access: needsNet, writable_roots: writable },
    };
    const domains = needsNet ? `\n# Network is a single on/off switch in this form. Hosts your history needed:\n# ${policy.network.allowDomains.join(", ")}\n# Use --codex-profile to emit a per-domain permissions profile instead.\n` : "";
    return `${header}\n${tomlStringify(doc)}\n${domains}`;
  }

  const filesystem: Record<string, string> = {};
  for (const w of writable) filesystem[w] = "write";
  for (const s of policy.filesystem.denyRead.filter((p) => !p.startsWith("./"))) filesystem[s] = "deny";
  const domains: Record<string, string> = {};
  for (const d of policy.network.allowDomains) domains[d] = "allow";
  const doc: Record<string, unknown> = {
    default_permissions: "sandfit",
    // Codex enforces a profile's per-domain rules only through its network proxy.
    ...(needsNet ? { features: { network_proxy: true } } : {}),
    permissions: {
      sandfit: {
        // :workspace makes the project writable and keeps .git/, .agents/ and .codex/ read-only.
        extends: ":workspace",
        description: `Least-privilege profile generated by ${policy.generatedBy}`,
        filesystem,
        network: { enabled: needsNet, domains },
      },
    },
  };
  return `${header}\n# Permission profiles are in beta in Codex and may change. Do not combine them with sandbox_mode:\n# when sandbox_mode is set anywhere, Codex ignores the profile.\n${tomlStringify(doc)}\n`;
}

/**
 * nono profile (~/.config/nono/profiles/<name>.json). nono wraps the whole agent process.
 * Paths use $HOME and $WORKDIR because nono does not expand ~ or relative paths.
 * Docs: https://nono.sh
 */
export function toNonoProfile(policy: Policy, name = "sandfit"): Record<string, unknown> {
  const nonoPath = (p: string) => (p.startsWith("~/") ? `$HOME/${p.slice(2)}` : p === "~" ? "$HOME" : p.startsWith("./") ? `$WORKDIR/${p.slice(2)}` : p);
  const allow = uniq([...policy.filesystem.allowWrite, ...policy.harnessTools.allowWrite, ...HARNESS_DIRS.filter((d) => !d.endsWith(".json"))]).map(nonoPath);
  const allowFile = HARNESS_DIRS.filter((d) => d.endsWith(".json")).map(nonoPath);
  const deny = policy.filesystem.denyRead.filter((p) => !p.includes("*")).map(nonoPath);
  const profile: Record<string, unknown> = {
    meta: { name, description: `Generated by ${policy.generatedBy} from ${policy.source.sessions} session${policy.source.sessions === 1 ? "" : "s"}` },
    workdir: { access: "readwrite" },
    filesystem: { allow, allow_file: allowFile, deny },
    network: { block: false, allow_domain: uniq([...policy.network.allowDomains, ...policy.harnessTools.allowFetch]) },
  };
  return profile;
}

/** The reviewable policy file: the source of truth every target is generated from. */
export function toPolicyYaml(policy: Policy): string {
  return `# sandfit policy: review this, then emit it for your sandbox.\n# Every grant lists how often your agent needed it and one example (credentials redacted).\n${yamlStringify(policy, { lineWidth: 0 })}`;
}

function uniq<T>(xs: T[]): T[] {
  return [...new Set(xs)];
}
