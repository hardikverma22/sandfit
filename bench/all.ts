/**
 * Run every benchmark and write BENCHMARKS.md from the results.
 *
 *   npm run bench                  accuracy + performance + real sandbox (if it can run here)
 *   npm run bench -- --no-sandbox  skip the real-sandbox benchmark
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { arch, cpus, platform, release } from "node:os";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const tsx = (script: string, ...args: string[]) => {
  const r = spawnSync(process.execPath, ["--import", "tsx", `bench/${script}`, ...args], { cwd: ROOT, encoding: "utf8", timeout: 30 * 60_000 });
  return { ok: r.status === 0, out: (r.stdout ?? "").trim(), err: (r.stderr ?? "").trim() };
};

console.error("accuracy…");
const accuracy = tsx("accuracy.ts");
console.error("performance…");
const perf = tsx("perf.ts");
let sandbox = { ok: false, out: "", err: "skipped (--no-sandbox)" };
if (!process.argv.includes("--no-sandbox")) {
  console.error("real sandbox…");
  sandbox = tsx("sandbox.ts");
}

const date = new Date().toISOString().slice(0, 10);
const md = `# Benchmarks

Generated by \`npm run bench\` on ${date} · ${platform()} ${release()} (${arch()}) · ${cpus()[0]?.model ?? "unknown CPU"} · Node ${process.version}

There are three benchmarks. Each one answers a question you should ask before trusting a
security tool with your workflow. Every number here comes from running the code in
[\`bench/\`](bench); run \`npm run bench\` to reproduce it on your machine.

## 1. Does sandfit work out what each command needs?

sandfit reads a command like \`pnpm --filter web dev\` and has to work out that it needs to
listen on a local port, or that \`pip install\` needs \`pypi.org\` and \`~/.cache/pip\`.
We wrote down, by hand, what 200+ commands coding agents commonly run really need, and score sandfit against it.

- **Precision**: of the things sandfit says a command needs, how many are real. Low precision means the policy allows more than necessary.
- **Recall**: of the things a command really needs, how many sandfit found. Low recall means the sandbox would block something you use.

The **holdout set** is the honest number: it was written after sandfit was tuned on the first set, and sandfit was not changed to fit it.

${accuracy.ok ? accuracy.out : `\n_Benchmark failed:_\n\n\`\`\`\n${accuracy.err}\n\`\`\``}

## 2. Is it fast enough on a big history?

Synthetic transcripts with a realistic mix of tool calls (commands from the labelled set, file
reads and edits, web fetches) and realistic size (about 13 KB per tool call; real transcripts are
mostly tool output). For scale: one developer's month of heavy Claude Code use was about 18,000 tool calls.
By default sandfit only reads the last 30 days, and skips transcript files older than that without opening them.

${perf.ok ? perf.out : `_Benchmark failed:_\n\n\`\`\`\n${perf.err}\n\`\`\``}

## 3. Does the forecast match a real sandbox?

sandfit says "this command would break" or "this would work". That is only useful if a real
sandbox agrees. This benchmark builds a policy from a small history, then runs probes inside
[Anthropic's sandbox-runtime](https://github.com/anthropics/sandbox-runtime) (bubblewrap on Linux,
Seatbelt on macOS): things the history needed (should work) and attacks a hijacked agent might
try (should be blocked: reading planted fake keys, editing \`~/.zshrc\`, writing git hooks,
reaching unknown hosts). It runs on every CI build, on Linux and macOS (\`npm run test:sandbox\`).

${sandbox.ok ? sandbox.out : `_Not run here: ${sandbox.err.split("\n")[0]}_`}

## What these numbers do not tell you

- The labelled commands are common ones. Your own tools may be missing from sandfit's knowledge
  base; \`npx sandfit\` lists them under "Tools sandfit has no knowledge of".
- A command can do things its text does not show (a script that calls an API). Those needs are
  invisible in history, so they are not in the policy until you run the command once with the sandbox on.
- The real-sandbox probes test sandbox-runtime, which Claude Code's sandbox is built on. Codex and
  nono use their own sandboxes; their configs are checked against their published schemas, not run.
`;
writeFileSync(`${ROOT}BENCHMARKS.md`, md);
console.error("wrote BENCHMARKS.md");
if (!accuracy.ok || !perf.ok) process.exitCode = 1;
